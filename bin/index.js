#!/usr/bin/env node

'use strict';

const path = require('path');
const detector = require('../src/detector');
const scaffolder = require('../src/scaffolder');
const stealth = require('../src/stealth');
const configLoader = require('../src/config');
const hookManager = require('../src/hook');
const llm = require('../src/llm');

const VALID_MODES = ['new', 'existing', 'auto'];

/**
 * Parse --mode=<value> from process.argv.
 * Returns { mode } or prints error + exits if invalid.
 */
function parseArgs(argv) {
  const modeArg = argv.find(arg => arg.startsWith('--mode='));
  const helpArg = argv.includes('--help') || argv.includes('-h');

  if (helpArg) {
    console.log(`
speckit-ai — Scaffold spec-driven AI workspace docs

Usage:
  npx speckit-ai [--mode=<mode>]

Options:
  --mode=new       (default) Generate Best Practices templates for your framework
  --mode=existing  Generate AI-PROMPT skeleton docs for an existing codebase
  --mode=auto      Auto-generate project docs based on your source code using LLM
  --init-hook      Install a native Git pre-commit hook to enforce SDD
  --help           Show this help message
`);
    process.exit(0);
  }

  if (argv.includes('--init-hook')) {
    return { initHook: true };
  }

  if (!modeArg) return { mode: 'new' };

  const mode = modeArg.split('=')[1];
  if (!VALID_MODES.includes(mode)) {
    console.error(`[speckit-ai] ❌ Invalid --mode="${mode}". Valid values: ${VALID_MODES.join(', ')}`);
    console.error('[speckit-ai] Run with --help to see usage.');
    process.exit(1);
  }

  return { mode };
}

async function main() {
  const parsedArgs = parseArgs(process.argv.slice(2));
  const targetDir = process.cwd();

  console.log('');
  
  if (parsedArgs.initHook) {
    console.log('[speckit-ai] 🚀 Installing Native Git Hook...');
    const success = hookManager.installHook(targetDir);
    if (!success) {
      process.exit(1);
    }
    console.log('');
    return;
  }

  const { mode } = parsedArgs;
  
  let autoGeneratedDocs = null;
  if (mode === 'auto') {
    console.log('[speckit-ai] 🤖 Mode: auto (AI Auto-generation)');
    console.log('[speckit-ai] 🔍 Scanning source code and requesting AI completion...');
    try {
      autoGeneratedDocs = await llm.generateDocs(targetDir);
      console.log('[speckit-ai] ✅ Successfully received AI completion!');
    } catch (err) {
      console.error(`[speckit-ai] ❌ Error: ${err.message}`);
      console.error('[speckit-ai] Falling back to --mode=new');
      process.exit(1);
    }
  } else {
    console.log(`[speckit-ai] ⚙️  Mode: ${mode === 'existing' ? 'existing (AI-PROMPT skeletons)' : 'new (Best Practices templates)'}`);
  }
  
  console.log('');

  // Step 1: Config
  const userConfig = configLoader.loadConfig(targetDir);
  const customTemplatesDir = userConfig.templatesDir || null;
  if (customTemplatesDir) {
    console.log(`[speckit-ai] ⚙️  Custom templates dir: ${customTemplatesDir}`);
  }

  // Step 2: Detect framework / structure
  const projectConfig = detector.detect(targetDir);
  if (projectConfig.type === 'single') {
    console.log(`[speckit-ai] 🔍 Detected: ${projectConfig.framework} / ${projectConfig.packageManager}`);
  } else {
    console.log(`[speckit-ai] 🔍 Detected Monorepo (${projectConfig.tool}) with ${projectConfig.subProjects.length} sub-projects`);
  }
  console.log('');

  // Step 3: Scaffold
  console.log('[speckit-ai] 📝 Creating documentation structure...');
  const { created, skipped } = scaffolder.scaffold({ targetDir, projectConfig, mode, customTemplatesDir, autoGeneratedDocs });
  console.log('');
  console.log(`[speckit-ai] ✅ ${created} file(s) created, ${skipped} file(s) skipped (already exist)`);
  console.log('');

  // Step 4: Stealth mode
  stealth.apply(targetDir);
  console.log('');

  // Done
  console.log('[speckit-ai] 🎉 Done!');
  if (mode === 'existing') {
    console.log('[speckit-ai] 👉 Next: ask your AI agent to read docs/ and fill in the AI-PROMPT sections based on the actual codebase.');
  } else {
    console.log('[speckit-ai] 👉 Next: open .agents/AGENTS.md and adjust it for your project.');
  }
  console.log('');
}

main().catch((err) => {
  console.error('[speckit-ai] ❌ Error:', err.message);
  process.exit(1);
});
